-- Fictional schema and objects for documentation only.
-- Demonstrates WITH, WHERE, GROUP BY, HAVING, SUM, COUNT, and INNER JOIN.
-- Assumed target datastore: FACT_PRODUCT_SALES
-- The example requires compatible source/target datastores to execute.

WITH SALES_CTE AS (
    SELECT
        S.PRODUCT_ID AS PRODUCT_ID,
        SUM(S.NET_AMOUNT) AS TOTAL_AMOUNT,
        COUNT(S.ORDER_ID) AS ORDER_COUNT
    FROM ODS.SALES_ORDERS S
    WHERE S.STATUS = 'COMPLETED'
    GROUP BY S.PRODUCT_ID
    HAVING SUM(S.NET_AMOUNT) > 1000
)
SELECT
    SC.PRODUCT_ID AS PRODUCT_ID,
    P.PRODUCT_NAME AS PRODUCT_NAME,
    P.CATEGORY_NAME AS CATEGORY_NAME,
    SC.TOTAL_AMOUNT AS TOTAL_AMOUNT,
    SC.ORDER_COUNT AS ORDER_COUNT
FROM SALES_CTE SC
INNER JOIN EDW.DIM_PRODUCT P
    ON SC.PRODUCT_ID = P.PRODUCT_ID;
